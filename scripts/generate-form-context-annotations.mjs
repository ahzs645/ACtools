#!/usr/bin/env node

import fs from "node:fs/promises";
import path from "node:path";
import process from "node:process";

const EXPECTED_HEADERS = [
  "SubSubSection",
  "Chart Field Label",
  "Form Context Field Name",
  "Field Type",
  "Description",
  "Populates Client Quick Look?",
  "Can Be Written Using Forms?",
  "Writes to AlayaAssessments?",
  "AlayaAssessments CA",
  "AlayaAssessments HC",
  "AlayaAssessment LTCH",
  "Note"
];

const inputArgument = process.argv[2];
const outputPath = process.argv[3]
  ? path.resolve(process.argv[3])
  : path.resolve("src/shared/formContextAnnotations.generated.ts");

if (!inputArgument) {
  console.error(
    "Usage: node scripts/generate-form-context-annotations.mjs <reference.tsv> [output.ts]"
  );
  process.exitCode = 1;
} else {
  const inputPath = path.resolve(inputArgument);
  const text = await fs.readFile(inputPath, "utf8");
  const rows = text.replace(/^\uFEFF/, "").split(/\r?\n/).filter((row) => row.length > 0);
  const headers = rows.shift()?.split("\t") ?? [];
  if (JSON.stringify(headers) !== JSON.stringify(EXPECTED_HEADERS)) {
    throw new Error(
      `Unexpected headers.\nExpected: ${EXPECTED_HEADERS.join(" | ")}\nReceived: ${headers.join(" | ")}`
    );
  }

  const annotations = rows.map((row, index) => {
    const cells = row.split("\t");
    if (cells.length !== EXPECTED_HEADERS.length) {
      throw new Error(`Row ${index + 2} has ${cells.length} columns; expected 12.`);
    }
    return {
      sourceRow: index + 2,
      subSubSection: cells[0].trim(),
      chartFieldLabel: cells[1].trim(),
      formContextFieldName: cells[2].trim(),
      displayType: cells[3].trim(),
      description: cells[4].trim(),
      populatesClientQuickLook: cells[5].trim(),
      writableFromForms: cells[6].trim(),
      writesToAlayaAssessments: cells[7].trim(),
      alayaAssessmentsCa: cells[8].trim(),
      alayaAssessmentsHc: cells[9].trim(),
      alayaAssessmentLtch: cells[10].trim(),
      note: cells[11].trim()
    };
  });

  const generated = `// Generated by scripts/generate-form-context-annotations.mjs.\n` +
    `// Source columns are intentionally preserved as strings for CSV fidelity.\n\n` +
    `export interface AlayaCareFormContextAnnotation {\n` +
    `  sourceRow: number;\n` +
    `  subSubSection: string;\n` +
    `  chartFieldLabel: string;\n` +
    `  formContextFieldName: string;\n` +
    `  displayType: string;\n` +
    `  description: string;\n` +
    `  populatesClientQuickLook: string;\n` +
    `  writableFromForms: string;\n` +
    `  writesToAlayaAssessments: string;\n` +
    `  alayaAssessmentsCa: string;\n` +
    `  alayaAssessmentsHc: string;\n` +
    `  alayaAssessmentLtch: string;\n` +
    `  note: string;\n` +
    `}\n\n` +
    `export const ALAYACARE_FORM_CONTEXT_ANNOTATIONS: AlayaCareFormContextAnnotation[] = ` +
    `${JSON.stringify(annotations, null, 2)};\n`;

  await fs.mkdir(path.dirname(outputPath), { recursive: true });
  await fs.writeFile(outputPath, generated, "utf8");
  console.log(`Wrote ${annotations.length} annotations to ${outputPath}`);
}
